def _term_rules(
    entity_type: str, terms: Sequence[str]
) -> List[Rule]:
    """Build one rule per term, capturing the term itself."""
    rules: List[Rule] = []
    for term in terms:
        rules.append(
            Rule(
                entity_type=entity_type,
                pattern=re.compile(
                    r"\b(" + re.escape(term) + r")\b", re.IGNORECASE
                ),
                context_words=(),
                label=f"term:{term}",
            )
        )
    return rules


def condition_rules() -> List[Rule]:
    """Rules for clinical conditions."""
    return _term_rules("PHI_DIAGNOSIS", CONDITIONS)


def medication_rules() -> List[Rule]:
    """Rules for medications and drugs."""
    return _term_rules("PHI_MEDICATION", MEDICATIONS)
